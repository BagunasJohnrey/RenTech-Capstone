/* One-off migration squash script (Phase 4.4).
 *
 * 1. Create a temporary schema on the live Postgres cluster (via DIRECT_URL).
 * 2. Move the existing (stale) prisma/migrations folder aside.
 * 3. `prisma migrate diff --from-empty --to-schema-datamodel` → baseline SQL.
 * 4. Write prisma/migrations/<ts>_squashed_baseline/migration.sql.
 * 5. `prisma migrate deploy` against the temp schema and `migrate diff` it
 *    back to `prisma/schema.prisma` to prove parity.
 * 6. `prisma migrate resolve --applied` on the LIVE public schema so prod
 *    records the baseline without running it.
 * 7. Drop the temp schema.
 *
 * Uses schemas (not a separate database) because no local Postgres is
 * available and creating another Supabase project just for a diff-check is
 * overkill. The temp schema isolates all DDL from the real tables.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const BACKEND = path.resolve(__dirname, '..');
const ENV_PATH = path.join(BACKEND, '.env');
const TEMP_SCHEMA = 'squash_tmp';

function readEnv() {
  const out = {};
  for (const line of fs.readFileSync(ENV_PATH, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.+?)\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function appendParam(url, key, value) {
  return url + (url.includes('?') ? '&' : '?') + `${key}=${encodeURIComponent(value)}`;
}

function prisma(args, opts = {}) {
  const env = { ...process.env, ...readEnv(), ...(opts.env || {}) };
  return execFileSync('npx', ['prisma', ...args], {
    cwd: BACKEND,
    env,
    stdio: opts.stdio || ['ignore', 'pipe', 'inherit'],
    input: opts.input,
    encoding: 'utf8',
    shell: true,
  });
}

function psql(url, sqlText) {
  const env = { ...process.env, ...readEnv() };
  return execFileSync('npx', ['prisma', 'db', 'execute', '--stdin', '--url', url], {
    cwd: BACKEND,
    env,
    input: sqlText,
    stdio: ['pipe', 'inherit', 'inherit'],
    shell: true,
  });
}

function main() {
  const env = readEnv();
  if (!env.DIRECT_URL) throw new Error('DIRECT_URL not found in backend/.env');

  const squashName = 'squashed_baseline';
  const migDir = path.join(BACKEND, 'prisma', 'migrations');
  const backupDir = `${migDir}.bak-${Date.now()}`;

  // ---- 1. Fresh temp schema
  console.log(`[squash] resetting temp schema "${TEMP_SCHEMA}"…`);
  psql(env.DIRECT_URL, `DROP SCHEMA IF EXISTS ${TEMP_SCHEMA} CASCADE; CREATE SCHEMA ${TEMP_SCHEMA};`);

  // ---- 2. Move stale migrations aside
  fs.renameSync(migDir, backupDir);
  fs.mkdirSync(migDir, { recursive: true });
  fs.writeFileSync(path.join(migDir, 'migration_lock.toml'),
    fs.readFileSync(path.join(backupDir, 'migration_lock.toml')));
  console.log('[squash] old migrations preserved at:', path.basename(backupDir));

  // ---- 3. Generate baseline SQL from the datamodel
  console.log('[squash] generating baseline SQL…');
  const diffSql = prisma(
    ['migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema.prisma', '--script'],
    { env: { DATABASE_URL: env.DATABASE_URL, DIRECT_URL: env.DIRECT_URL } }
  );

  // ---- 4. Write new baseline migration
  const stamp = new Date().toISOString().replace(/[-:T.Z]/g, '').slice(0, 14);
  const newMigName = `${stamp}_${squashName}`;
  const newMigDir = path.join(migDir, newMigName);
  fs.mkdirSync(newMigDir, { recursive: true });
  fs.writeFileSync(
    path.join(newMigDir, 'migration.sql'),
    `-- Squashed baseline migration (Phase 4.4, generated by scripts/squash-migrations.cjs)\n\n${diffSql}`
  );
  console.log('[squash] wrote:', newMigName);

  // ---- 5. Deploy to temp schema + check parity
  const tempUrl = appendParam(env.DIRECT_URL, 'schema', TEMP_SCHEMA);
  console.log('[squash] deploying baseline to temp schema…');
  prisma(['migrate', 'deploy', '--schema', 'prisma/schema.prisma'], {
    env: { DATABASE_URL: tempUrl, DIRECT_URL: tempUrl },
    stdio: 'inherit',
  });

  console.log('[squash] checking temp schema matches datamodel…');
  let drift = '';
  try {
    drift = prisma(
      ['migrate', 'diff', '--from-schema-datamodel', 'prisma/schema.prisma', '--to-url', tempUrl, '--script'],
      { env: { DATABASE_URL: tempUrl, DIRECT_URL: tempUrl } }
    );
  } catch (err) {
    // migrate diff exits non-zero when it would print something. In this case
    // it's expected (no drift → exit 0), so bail only if the call dies before
    // producing any stdout at all.
    if (!err.stdout) throw err;
    drift = err.stdout;
  }
  const meaningful = drift
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('--'));
  if (meaningful.length > 0) {
    console.error('[squash] drift detected in temp schema:\n' + meaningful.join('\n'));
    throw new Error('Deployed baseline does NOT match prisma/schema.prisma');
  }
  console.log('[squash] temp schema matches prisma/schema.prisma ✓');

  // Also verify the deploy targeted ONLY the temp schema (defensive log).
  // prisma db execute does not echo results, so we just confirm it ran cleanly.
  psql(tempUrl,
    `SELECT count(*) FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE';`
  );

  // ---- 6. Mark baseline as applied on the LIVE public schema
  const liveUrl = env.DIRECT_URL;
  console.log('[squash] marking baseline as applied on LIVE public schema…');
  prisma(['migrate', 'resolve', '--applied', newMigName, '--schema', 'prisma/schema.prisma'], {
    env: { DATABASE_URL: liveUrl, DIRECT_URL: liveUrl },
    input: 'y\n',
  });

  const liveStatus = prisma(['migrate', 'status', '--schema', 'prisma/schema.prisma'], {
    env: { DATABASE_URL: liveUrl, DIRECT_URL: liveUrl },
  });
  console.log('[squash] live status:\n', liveStatus);

  // ---- 7. Cleanup
  console.log('[squash] dropping temp schema…');
  psql(env.DIRECT_URL, `DROP SCHEMA IF EXISTS ${TEMP_SCHEMA} CASCADE;`);

  console.log('[squash] DONE.');
  console.log('[squash] Next: stop the backend, run "npx prisma generate", restart.');
  console.log('[squash] If everything is green you can delete:', path.basename(backupDir));
}

try {
  main();
} catch (err) {
  console.error('[squash] FAILED:', err && err.message ? err.message : err);
  process.exit(1);
}
