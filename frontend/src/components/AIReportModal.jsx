import { useState } from 'react';
import { X, Sparkles, Download, Loader2, AlertCircle } from 'lucide-react';
import { parseReportSections } from '../utils/formatReport';
import { generateReportPdf } from '../utils/reportPdf';

const COMPANY = "Mylene's Boutique";
const TAGLINE = 'Rental Attire & Formal Wear';
const ADDRESS = 'Balayan, Batangas, Philippines';
const ACCENT = '#bf4a53';

export default function AIReportModal({ geminiReport, onClose }) {
  const sections = geminiReport ? parseReportSections(geminiReport) : [];
  const generatedDate = new Date().toLocaleDateString('en-PH', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });
  const docRef = `MB-RPT-${new Date().getFullYear()}-${String(
    new Date().getMonth() + 1
  ).padStart(2, '0')}`;

  const [downloading, setDownloading] = useState(false);
  const handleDownloadPdf = () => {
    try {
      setDownloading(true);
      generateReportPdf(sections, { generatedDate, docRef });
    } catch (err) {
      console.error('PDF generation failed', err);
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div
      className="fixed inset-0 bg-gray-900/40 backdrop-blur-sm z-[100] flex items-center justify-center p-4"
      onClick={onClose}
    >
      <div
        className="bg-white rounded-3xl shadow-2xl w-full max-w-3xl max-h-[92vh] overflow-hidden flex flex-col animate-in fade-in zoom-in-95 duration-300"
        onClick={(e) => e.stopPropagation()}
      >
        {/* On-screen modal header (not printed) */}
        <div className="flex justify-between items-center p-5 border-b border-gray-100/80 bg-gradient-to-r from-red-50 to-white no-print">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl text-white" style={{ backgroundColor: ACCENT }}>
              <Sparkles size={20} />
            </div>
            <div>
              <h3 className="font-bold text-lg text-gray-900">AI Business Report</h3>
              <p className="text-xs text-gray-500">Powered by Gemini · Real-time analytics</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="text-gray-400 hover:bg-gray-200 p-2 rounded-full transition-colors"
          >
            <X size={20} />
          </button>
        </div>

        {/* Scrollable report body */}
        <div className="overflow-y-auto flex-1 custom-scrollbar bg-gray-50/40">
          {!geminiReport ? (
            <div className="flex flex-col items-center justify-center py-20 space-y-3">
              <AlertCircle size={32} className="text-gray-300" />
              <p className="text-sm text-gray-500">AI report could not be generated. Please try again.</p>
            </div>
          ) : (
            <div id="report-print-area" className="report-document bg-white mx-auto my-6 max-w-[780px] shadow-sm rounded-xl">
              {/* Business letterhead */}
              <header className="report-header" style={{ borderTopColor: ACCENT }}>
                <div className="flex items-start justify-between gap-4">
                  <div>
                    <h1 className="report-company" style={{ color: ACCENT }}>{COMPANY}</h1>
                    <p className="report-tagline">{TAGLINE}</p>
                    <p className="report-address">{ADDRESS}</p>
                  </div>
                  <div className="text-right">
                    <p className="report-doc-title">Business Performance Report</p>
                    <p className="report-meta">Date: {generatedDate}</p>
                    <p className="report-meta">Ref: {docRef}</p>
                  </div>
                </div>
                <hr className="report-rule" style={{ borderColor: ACCENT }} />
              </header>

              {/* Sections */}
              <div className="report-body">
                {sections.map((section, idx) => (
                  <section key={idx} className="report-section">
                    {section.title && (
                      <h2 className="report-section-title" style={{ color: ACCENT }}>
                        {section.title}
                      </h2>
                    )}
                    <div className="report-section-content">
                      {section.bodyLines.map((line, i) => (
                        <p key={i} className="report-line">
                          {line}
                        </p>
                      ))}
                    </div>
                  </section>
                ))}
              </div>

              {/* Footer */}
              <footer className="report-footer">
                <p>
                  Generated by {COMPANY} AI Analytics · This report is confidential and intended for
                  management use only.
                </p>
              </footer>
            </div>
          )}
        </div>

        {/* On-screen footer actions (not printed) */}
        <div className="p-4 border-t border-gray-100/80 bg-gray-50/50 flex justify-between items-center no-print">
          <p className="text-xs text-gray-400">Generated by Gemini (server)</p>
            <button
              onClick={handleDownloadPdf}
              disabled={!geminiReport || downloading}
              className="px-5 py-2 text-white text-xs font-semibold rounded-full transition-colors flex items-center gap-1.5 disabled:opacity-50"
              style={{ backgroundColor: ACCENT }}
            >
              {downloading ? <Loader2 size={14} className="animate-spin" /> : <Download size={14} />}
              {downloading ? 'Generating…' : 'Download PDF'}
            </button>
        </div>
      </div>
    </div>
  );
}
